let idiomaAtual = localStorage.getItem("idioma") || "pt";
if (!textos[idiomaAtual]) idiomaAtual = "pt";

function t(chave) {
  return textos[idiomaAtual][chave];
}

function traduzir(idioma) {
  idiomaAtual = idioma;

  document.querySelectorAll("[data-i18n]").forEach((el) => {
    el.textContent = textos[idioma][el.dataset.i18n];
  });

  document.documentElement.lang = idioma === "pt" ? "pt-BR" : idioma;
  document.title = textos[idioma].titulo_pagina;

  document.querySelectorAll(".idioma button").forEach((b) => {
    b.classList.toggle("ativo", b.dataset.idioma === idioma);
  });

  localStorage.setItem("idioma", idioma);
}

document.querySelectorAll(".idioma button").forEach((b) => {
  b.addEventListener("click", () => traduzir(b.dataset.idioma));
});

traduzir(idiomaAtual);